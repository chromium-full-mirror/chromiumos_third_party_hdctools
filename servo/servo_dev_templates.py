# SERVO_VID_PID_TEMPLATE_MAP, SERVO_LOTID_TEMPLATE_MAP and SERVO_ID_DEFAULTS gets
# populated on module import to keep a single source of truth about the device
# information - their template classes.
# A 2d map to fetch a servo device template given a vendor id and a product id.
SERVO_VID_PID_TEMPLATE_MAP = collections.defaultdict(lambda: collections.defaultdict(set))
# A dict to fetch a servo device template given a lot id.
SERVO_LOTID_TEMPLATE_MAP = collections.defaultdict(set)
# A set of tuples of the vid/pid pairs of all known servo devices.
SERVO_ID_DEFAULTS = set()

# Lot IDs are used to distinguish between servo v2 and servo v2 r0. If a device
# has a lot-id that is not known, it gets assigned a fake lot id to ensure that
# it registers as v2 as after a while all the new(er) lotids are v2.
FORCE_V2_LOTID = 'force-v2-lotid'

class DeviceTemplateError(Exception):
  """Error class for device templates."""
  pass

def GetTemplateClass(vid, pid, serial=None):
  """Get the ServoDevTemplate class associated with (vid, pid, serial).

  Note: the serialname is only used when (vid, pid) leave ambiguity (more than
  one template class) and the serialname is needed to determine the lot-id

  Args:
    vid: vendor id for a servo device
    pid: product id for a servo device
    serial: serialname of servo device in question

  Returns:
    servo dev template class associated with (vid, pid, serial)

  Raises:
    DeviceTemplateError if template class not found, or not uniquely identified
  """
  dev_class_candidates = SERVO_VID_PID_TEMPLATE_MAP[vid][pid].copy()
  if len(dev_class_candidates) > 1:
    # Might need the lotid to distinguish what device is used.
    if serial:
      try:
        lotid, _ = serial.split('-')
        logging.info('Retrieved lot-id %r for sid: %r.', lotid, serial)
      except ValueError:
        logging.debug('Could not retrieve lot-id for sid: %r.', serial)
        lotid = ''
      if lotid not in SERVO_LOTID_TEMPLATE_MAP:
        # This usually means that it's a servo-v2 and not servo-v2-r0, so
        # assign a fake lot-id to force servo-v2.
        logging.info('Lotid %r not in lotid map. Assigning fake lot id '
                     'to force servo v2 selection.', lotid)
        lotid = FORCE_V2_LOTID
      dev_class_candidates &= SERVO_LOTID_TEMPLATE_MAP[lotid]
  dev_str = '[%04x:%04x%s]' % (vid, pid, ' ' + serial if serial else '')
  if not dev_class_candidates:
    logging.error('Could not find a ServoDev class for %s.', dev_str)
    return None
  if len(dev_class_candidates) > 1:
    logging.error('Multiple ServoDev template classes found for %s. This '
                  'should not happen.', dev_str)
    for dev_class in dev_class_candidates:
      logging.error('Found ServoDev template class %s', dev_class.__name__)
    return None
  return dev_class_candidates.pop()

def _CamelToSnakeCase(iput):
  """Convert CamelCase to snake_case, and remove trailing underscores.
  Substitute each upper-case letter preceded by a lower-case one (or number)
  with a _ and its lower case equivalent.
  Args:
    iput: input string to convert
  Returns:
    iput string converted to camel-case
  """
  s1 = re.sub('(.)([A-Z][a-z]+)', r'\1_\2', iput)
  return re.sub('([a-z0-9])([A-Z])', r'\1_\2', s1).rstrip('_').lower()

class _ServoDevTemplate(object):
  """Base servo device template class.
  Servo device template classes are classes to centrally collect information
  about a servo device. This us to quickly answer questions about different
  servo devices, and to abstract capabilities from device types/names by
  having different capabilities just be attributes.
  """

  # The Vendor ID associated with this servo device
  VID = None
  # The product ID associated with this servo device
  PID = None
  # A tuple of (VID, PID). This is autogenerated.
  ID = None
  # For some servo devies, different lot ids (from serialname) identify the
  # template class
  LOTIDS = None
  # The default configuration file to pull in for this servo device
  DEFAULT_CONFIG = None
  # The type string of a servo device
  TYPE = 'unknown'
  # The ServoDev class used for the servo device
  DEV_CONSTRUCTOR = None

