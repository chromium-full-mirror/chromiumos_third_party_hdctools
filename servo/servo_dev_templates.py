def _InitMaps(servo_dev_module):
  """Helper to initialize the vid/pid/lotid maps for easy retrieval.
  This helper gets called on module import to populate the vid/pid/lotid
  maps with the right classes, to facilitate retrieval of the template class.
  It also calls GenerateType on each class to ensure that the type string
  is properly setup.
  Args:
    servo_dev_module: a reference to this very module
  """
  classes = inspect.getmembers(servo_dev_module, inspect.isclass)
  for cname, c in classes:
    if cname.endswith('Error'):
      continue
    if c.VID and c.PID:
      # This means the class refers to a physical servo device class.
      # Generate the servo device ID - (vid, pid)
      c.ID = (c.VID, c.PID)
      # Populate the SERVO_ID_DEFAULTS set
      SERVO_ID_DEFAULTS.add(c.ID)
      # Populate the lookup maps to allow for retrieval.
      SERVO_VID_PID_TEMPLATE_MAP[c.VID][c.PID].add(c)
      if c.LOTIDS:
        for lotid in c.LOTIDS:
          SERVO_LOTID_TEMPLATE_MAP[lotid].add(c)
# on import, run initialization
_InitMaps(sys.modules[__name__])
